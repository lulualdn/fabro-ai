// Generates src/renderer/icons-data.js from Heroicons (solid) + Phosphor (fill) for gaps.
// Run: node scripts/build-icons.js
const fs = require('fs');
const path = require('path');
const HERO = path.join(__dirname, '..', 'node_modules', 'heroicons', '24', 'solid');
const PHOS = path.join(__dirname, '..', 'node_modules', '@phosphor-icons', 'core', 'assets', 'fill');

// app name -> 'hero:<file>' | 'ph:<file>'
const MAP = {
  plus: 'hero:plus', chat: 'hero:chat-bubble-oval-left', folder: 'hero:folder', agent: 'ph:robot-fill',
  code: 'hero:code-bracket', lock: 'hero:lock-closed', unlock: 'hero:lock-open', settings: 'hero:cog-6-tooth',
  panel: 'ph:sidebar-simple-fill', up: 'hero:arrow-up', stop: 'hero:stop', copy: 'hero:document-duplicate',
  check: 'hero:check', retry: 'hero:arrow-path', clip: 'hero:paper-clip', x: 'hero:x-mark',
  down: 'hero:chevron-down', right: 'hero:chevron-right', download: 'hero:arrow-down-tray', upload: 'hero:arrow-up-tray',
  cpu: 'hero:cpu-chip', trash: 'hero:trash', search: 'hero:magnifying-glass', image: 'hero:photo',
  video: 'hero:video-camera', file: 'hero:document-text', expand: 'hero:arrows-pointing-out', globe: 'hero:globe-alt',
  zap: 'hero:bolt', box: 'hero:cube', info: 'hero:information-circle', sun: 'hero:sun', moon: 'hero:moon',
  monitor: 'hero:computer-desktop', sliders: 'hero:adjustments-horizontal', brain: 'ph:brain-fill',
  refresh: 'hero:arrow-path', edit: 'hero:pencil-square', power: 'hero:power', back: 'hero:arrow-left',
  forward: 'hero:arrow-right', shapes: 'hero:squares-2x2', tasks: 'hero:clock', brush: 'hero:paint-brush',
  pin: 'ph:push-pin-fill', filter: 'hero:funnel', agentBadge: 'ph:robot-fill', dots: 'hero:ellipsis-horizontal',
  mic: 'hero:microphone', waveform: 'ph:waveform-fill', camera: 'hero:video-camera', share: 'hero:share',
  link: 'hero:link', star: 'hero:star', warning: 'hero:exclamation-triangle', error: 'hero:x-circle',
  success: 'hero:check-circle', bell: 'hero:bell', user: 'hero:user-circle', key: 'hero:key', cloud: 'hero:cloud',
  wifi: 'hero:wifi', server: 'hero:server-stack', puzzle: 'hero:puzzle-piece', wrench: 'hero:wrench',
  book: 'hero:book-open', layers: 'hero:square-3-stack-3d', terminal: 'hero:command-line', play: 'hero:play',
  pause: 'hero:pause', table: 'hero:table-cells', chart: 'hero:chart-bar', language: 'hero:language',
  shield: 'hero:shield-check', eye: 'hero:eye', eyeOff: 'hero:eye-slash', calendar: 'hero:calendar-days',
  archive: 'hero:archive-box', slides: 'hero:presentation-chart-bar', rocket: 'hero:rocket-launch',
};

const out = {};
for (const [name, ref] of Object.entries(MAP)) {
  const [set, file] = ref.split(':');
  const svg = fs.readFileSync(path.join(set === 'hero' ? HERO : PHOS, file + '.svg'), 'utf8');
  const vb = (svg.match(/viewBox="([^"]+)"/) || [])[1];
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s(fill|stroke)="(?!none)[^"]*"/g, '').replace(/\s+/g, ' ').trim();
  out[name] = [vb, body];
}
const header = '// Generated by scripts/build-icons.js — Heroicons (MIT) solid + Phosphor (MIT) fill. Do not edit.\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'icons-data.js'), header + 'const ICON_DATA = ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).length, 'icons');
